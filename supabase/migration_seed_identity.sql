-- HRSuite seed compatibility migration
-- The app's demo seed uses stable IDs to preserve foreign-key relationships.
-- Tables created with GENERATED ALWAYS reject those explicit IDs through PostgREST.
-- Allow explicit IDs while retaining identity generation for normal inserts.
-- Run once in Supabase SQL Editor, then reload the app.

do $$
declare
  col record;
begin
  for col in
    select table_schema, table_name, column_name
    from information_schema.columns
    where table_schema = 'public'
      and column_name = 'id'
      and identity_generation = 'ALWAYS'
  loop
    execute format(
      'alter table %I.%I alter column %I set generated by default',
      col.table_schema, col.table_name, col.column_name
    );
  end loop;
end $$;
